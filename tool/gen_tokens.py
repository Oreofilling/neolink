#!/usr/bin/env python3
"""RETIRED (v7d design pass, 2026-11): tokens.dart is hand-maintained now.
Running this script would clobber the hand-tuned v7d token set — kept only
for history. Source of truth: docs/design-rules.md + tokens.dart itself.

Legacy description: 再生成 packages/neolink_ui/lib/src/tokens.dart。

用法:
  python3 tool/gen_tokens.py [原型CSS路径] [输出dart路径]
默认原型: lowpower_camera/docs/neolink_ui_mockup.html（NL 设计系统 OKLCH 令牌）。
亮/暗两套全量色彩 + 圆角 + 时长；行尾注释保留原始 OKLCH 表达式。
"""
import math
import re
import sys
from pathlib import Path

DEFAULT_CSS = "/home/work/lowpower_camera/docs/neolink_ui_mockup.html"
DEFAULT_OUT = Path(__file__).resolve().parents[1] / "packages/neolink_ui/lib/src/tokens.dart"


def oklch_to_argb(val: str):
    m = re.match(r"oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*/\s*([\d.]+)%?)?\)", val)
    if not m:
        return None
    L, C, H = map(float, m.group(1, 2, 3))
    a = float(m.group(4)) / 100 if m.group(4) else 1.0
    h = math.radians(H)
    la, lb = C * math.cos(h), C * math.sin(h)
    l_ = L + 0.3963377774 * la + 0.2158037573 * lb
    m_ = L - 0.1055613458 * la - 0.0638541728 * lb
    s_ = L - 0.0894841775 * la - 1.2914855480 * lb
    l, mm, s = l_ ** 3, m_ ** 3, s_ ** 3
    lr = 4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s
    lg = -1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s
    lbv = -0.0041960863 * l - 0.7034186147 * mm + 1.7076147010 * s

    def gamma(c: float) -> float:
        c = max(0.0, min(1.0, c))
        return 12.92 * c if c <= 0.0031308 else 1.055 * (c ** (1 / 2.4)) - 0.055

    r, g, b = (round(gamma(v) * 255) for v in (lr, lg, lbv))
    return (round(a * 255) << 24) | (r << 16) | (g << 8) | b


def camel(n: str) -> str:
    p = n.lstrip("-").split("-")
    return p[0] + "".join(x.title() for x in p[1:])


def convert(block: dict):
    colors, radii, durs = {}, {}, {}
    for k, v in block.items():
        argb = oklch_to_argb(v)
        if argb is None and v.startswith("#"):
            hm = re.match(r"#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?", v)
            if hm:
                a = int(hm.group(2), 16) if hm.group(2) else 255
                argb = (a << 24) | int(hm.group(1), 16)
        if argb is not None:
            colors[camel(k)] = (argb, v)
            continue
        rm, pm, dmz = re.match(r"([\d.]+)rem$", v), re.match(r"([\d.]+)px$", v), re.match(r"(\d+)ms$", v)
        if rm:
            radii[camel(k)] = float(rm.group(1)) * 16
        elif pm:
            radii[camel(k)] = float(pm.group(1))
        elif dmz:
            durs[camel(k)] = int(dmz.group(1))
    return colors, radii, durs


def main() -> None:
    css_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_CSS
    out_path = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUT
    css = open(css_path, encoding="utf-8").read()

    def parse_block(pattern: str) -> dict:
        m = re.search(pattern, css, re.S)
        d = {}
        if not m:
            return d
        for line in m.group(1).splitlines():
            dm = re.match(r"\s*(--[\w-]+)\s*:\s*([^;]+);", line)
            if dm:
                d[dm.group(1)] = dm.group(2).strip()
        return d

    light_raw, dark_raw = parse_block(r":root\s*\{(.*?)\}"), parse_block(r"\.dark\s*\{(.*?)\}")
    assert light_raw and dark_raw, "未找到 :root / .dark 令牌块"
    lc, lr_, ld = convert(light_raw)
    dc, dr_, dd = convert(dark_raw)
    for side, other in ((lc, dc), (dc, lc)):
        for k in list(other):
            side.setdefault(k, other[k])
    need = {"background", "foreground", "card", "muted", "mutedForeground", "border", "primary",
            "primaryForeground", "success", "warning", "error", "info", "cardHoverBg"}
    missing = need - set(lc)
    assert not missing, f"缺少令牌: {missing}; 实际: {sorted(lc)}"
    ld.setdefault("fast", 150)
    ld.setdefault("normal", 300)
    keys = sorted(set(lc) | set(dc))

    def lit(k, side):
        src = (lc if side == "light" else dc).get(k) or lc[k]
        return "Color(0x%08X)" % src[0]

    def comment(k, side):
        return ((lc if side == "light" else dc).get(k) or lc[k])[1]

    T = ["// GENERATED by tool/gen_tokens.py — 勿手改。",
         f"// 来源：{css_path}（NL 设计系统 OKLCH 令牌）。",
         "// 行尾注释保留原始 OKLCH 表达式，便于回溯再生成。",
         "import 'package:flutter/material.dart';", "",
         "/// 全量色彩令牌（亮/暗两套），经 ThemeExtension 注册；Widget 侧用 `context.nl.xxx` 访问。",
         "class NLColors extends ThemeExtension<NLColors> {",
         "  const NLColors({"]
    T.append("".join("    required this.%s, // %s | %s\n" % (k, comment(k, "light"), comment(k, "dark")) for k in keys).rstrip("\n"))
    T.append("  });")
    T.append("")
    T.append("".join("  final Color %s;\n" % k for k in keys).rstrip("\n"))
    T.append("")
    T.append("  static const light = NLColors(")
    T.append("".join("    %s: %s,\n" % (k, lit(k, "light")) for k in keys).rstrip("\n"))
    T.append("  );")
    T.append("  static const dark = NLColors(")
    T.append("".join("    %s: %s,\n" % (k, lit(k, "dark")) for k in keys).rstrip("\n"))
    T.append("  );")
    T.append("")
    T.append("  @override")
    T.append("  NLColors copyWith({")
    T.append("".join("    Color? %s,\n" % k for k in keys).rstrip("\n"))
    T.append("  }) => NLColors(")
    T.append("".join("    %s: %s ?? this.%s,\n" % (k, k, k) for k in keys).rstrip("\n"))
    T.append("  );")
    T.append("")
    T.append("  @override")
    T.append("  NLColors lerp(NLColors? other, double t) => other == null")
    T.append("      ? this")
    T.append("      : NLColors(")
    T.append("".join("        %s: Color.lerp(%s, other.%s, t)!,\n" % (k, k, k) for k in keys).rstrip("\n"))
    T.append("      );")
    T.append("}")
    T.append("")
    T.append("/// 圆角令牌（rem→logical px）。")
    T.append("abstract final class NLRadii {")
    T.append("".join("  static const %s = %g;\n" % (k, v) for k, v in sorted(lr_.items())).rstrip("\n"))
    T.append("}")
    T.append("")
    T.append("/// 动画时长令牌。")
    T.append("abstract final class NLDurations {")
    T.append("".join("  static const %s = Duration(milliseconds: %d);\n" % (k, v) for k, v in sorted(ld.items())).rstrip("\n"))
    T.append("}")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(T) + "\n", encoding="utf-8")
    print("written: %s (%d colors, %d radii, %d durations)" % (out_path, len(keys), len(lr_), len(ld)))


if __name__ == "__main__":
    main()
